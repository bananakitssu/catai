def _clean_string(value: object) -> str:
    return " ".join(value.split()) if isinstance(value, str) else ""


def _parse_json_object(value: object) -> dict[str, Any] | None:
    if isinstance(value, dict):
        return value
    if isinstance(value, str):
        try:
            parsed = json.loads(value)
        except json.JSONDecodeError:
            return None
        return parsed if isinstance(parsed, dict) else None
    return None


def _normalize_two_speaker_turns(
    turns: object,
    *,
    speaker_key: str,
    text_key: str,
) -> list[dict[str, str]] | None:
    if not isinstance(turns, list):
        return None
    clean_turns: list[tuple[str, str]] = []
    for turn in turns:
        if not isinstance(turn, dict):
            return None
        speaker = _clean_string(turn.get(speaker_key))
        text = _clean_string(turn.get(text_key))
        if not speaker or not text:
            return None
        clean_turns.append((speaker, text))
    speakers = list(dict.fromkeys(speaker for speaker, _ in clean_turns))
    if len(speakers) != 2:
        return None
    role_by_speaker = {speakers[0]: "user", speakers[1]: "assistant"}
    messages = [
        {"role": role_by_speaker[speaker], "content": text}
        for speaker, text in clean_turns
    ]
    # Some dialogue corpora end with an unfinished user turn. Drop that tail
    # rather than emitting a supervised example without a target assistant reply.
    while messages and messages[-1]["role"] != "assistant":
        messages.pop()
    if len(messages) < 2:
        return None
    try:
        normalized = validate_messages(messages)
    except ValueError:
        return None
    return normalized


def convert_soda_row(row: dict[str, Any]) -> list[dict[str, str]] | None:
    dialogue = row.get("dialogue")
    speakers = row.get("speakers")
    if not isinstance(dialogue, list) or not isinstance(speakers, list):
        return None
    if len(dialogue) != len(speakers):
        return None
    turns = [
        {"speaker": speaker, "text": text}
        for speaker, text in zip(speakers, dialogue)
    ]
    return _normalize_two_speaker_turns(
        turns, speaker_key="speaker", text_key="text"
    )


def convert_everyday_conversations_row(row: dict[str, Any]) -> list[dict[str, str]] | None:
    messages = normalize_messages(row.get("messages"))
    if messages is not None:
        return messages
    prompt = _clean_string(row.get("prompt"))
    completion = _clean_string(row.get("completion"))
    if prompt and completion:
        return normalize_messages([
            {"role": "user", "content": prompt},
            {"role": "assistant", "content": completion},
        ])
    return None


def convert_english_daily_dialogues_row(row: dict[str, Any]) -> list[dict[str, str]] | None:
    turns = row.get("turns")
    return _normalize_two_speaker_turns(
        turns, speaker_key="speaker", text_key="text"
    )


def convert_synthetic_social_dialogues_row(row: dict[str, Any]) -> list[dict[str, str]] | None:
    output = _parse_json_object(row.get("output"))
    if output is None:
        return None
    return _normalize_two_speaker_turns(
        output.get("dialogue"), speaker_key="speaker", text_key="line"
    )


def convert_synthetic_conversations_row(row: dict[str, Any]) -> list[dict[str, str]] | None:
    return normalize_messages(row.get("conversations"))


def convert_multiwoz_dialogue(dialogue: object) -> list[dict[str, str]] | None:
    if not isinstance(dialogue, dict):
        return None
    turns = dialogue.get("turns")
    if not isinstance(turns, list):
        return None
    converted = []
    for turn in turns:
        if not isinstance(turn, dict):
            return None
        speaker = str(turn.get("speaker", "")).strip().upper()
        utterance = _clean_string(turn.get("utterance"))
        if speaker not in {"USER", "SYSTEM"} or not utterance:
            return None
        converted.append({
            "role": "user" if speaker == "USER" else "assistant",
            "content": utterance,
        })
    try:
        return validate_messages(converted)
    except ValueError:
        return None


