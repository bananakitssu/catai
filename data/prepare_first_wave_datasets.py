def make_record(
    source: str,
    messages: list[dict[str, str]],
    *,
    repository: str,
    license_name: str,
    attribution: str,
    split: str,
    source_id: object = None,
    notes: str = "",
) -> dict[str, Any]:
    record: dict[str, Any] = {
        "state": default_state(),
        "messages": messages,
        "dataset_source": source,
        "dataset_license": license_name,
        "dataset_repository": repository,
        "dataset_split": split,
        "dataset_attribution": attribution,
    }
    if source_id not in (None, ""):
        record["dataset_record_id"] = str(source_id)
    if notes:
        record["dataset_notes"] = notes
    return record


def _download_bytes(url: str, *, attempts: int = 6) -> bytes:
    last_error: BaseException | None = None
    for attempt in range(attempts):
        request = urllib.request.Request(
            url, headers={"User-Agent": "CatAI-first-wave-datasets/1.0"}
        )
        try:
            with urllib.request.urlopen(request, timeout=180) as response:
                payload = response.read()
            if not payload:
                raise RuntimeError(f"empty download from {url}")
            return payload
        except urllib.error.HTTPError as exc:
            last_error = exc
            if exc.code not in {429, 500, 502, 503, 504}:
                raise
            delay = min(60, 2 ** (attempt + 1))
            retry_after = exc.headers.get("Retry-After") if exc.headers else None
            if retry_after:
                try:
                    delay = min(120, max(1, int(retry_after)))
                except ValueError:
                    pass
        except (urllib.error.URLError, TimeoutError, OSError) as exc:
            last_error = exc
            delay = min(60, 2 ** (attempt + 1))
        if attempt + 1 < attempts:
            time.sleep(delay)
    raise RuntimeError(f"download failed after {attempts} attempts: {url}") from last_error


def _download_multiwoz_examples(limit: int, seed: int) -> list[dict[str, Any]]:
    rng = random.Random(seed)
    names = list(MULTIWOZ_TRAIN_SHARDS)
    rng.shuffle(names)
    examples: list[dict[str, Any]] = []
    with tempfile.TemporaryDirectory(prefix="catai-multiwoz-") as temporary:
        for name in names:
            payload = _download_bytes(MULTIWOZ_BASE_URL + name)
            actual_hash = hashlib.sha256(payload).hexdigest()
            expected_hash = MULTIWOZ_TRAIN_SHARDS[name]
            if actual_hash != expected_hash:
                raise RuntimeError(
                    f"MultiWOZ integrity check failed for {name}: "
                    f"expected {expected_hash}, received {actual_hash}"
                )
            path = Path(temporary) / name
            path.write_bytes(payload)
            raw_dialogues = json.loads(path.read_text(encoding="utf-8"))
            if not isinstance(raw_dialogues, list):
                raise ValueError(f"MultiWOZ shard {name} did not contain a JSON list")
            for dialogue in raw_dialogues:
                messages = convert_multiwoz_dialogue(dialogue)
                if messages is None:
                    continue
                examples.append(make_record(
                    "multiwoz",
                    messages,
                    repository=MULTIWOZ_SPEC["repository"],
                    license_name=MULTIWOZ_SPEC["license"],
                    attribution=MULTIWOZ_SPEC["attribution"],
                    split="train",
                    source_id=dialogue.get("dialogue_id") if isinstance(dialogue, dict) else None,
                    notes=MULTIWOZ_SPEC["notes"],
                ))
    rng.shuffle(examples)
    return examples[:limit]


def _download_social_dialogue_rows(limit: int, seed: int) -> list[dict[str, Any]]:
    try:
        import zstandard
    except ImportError as exc:
        raise RuntimeError(
            "Synthetic Social Dialogues requires zstandard; install CatAI with .[data]."
        ) from exc

    compressed = _download_bytes(SOCIAL_DIALOGUES_URL)
    reservoir: list[dict[str, Any]] = []
    rng = random.Random(seed)
    seen = 0
    with zstandard.ZstdDecompressor().stream_reader(io.BytesIO(compressed)) as reader:
        import io as text_io
        stream = text_io.TextIOWrapper(reader, encoding="utf-8")
        for line in stream:
            if not line.strip():
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue
            if not isinstance(row, dict):
                continue
            seen += 1
            if len(reservoir) < limit:
                reservoir.append(row)
            else:
                index = rng.randrange(seen)
                if index < limit:
                    reservoir[index] = row
    if not reservoir:
        raise RuntimeError("Synthetic Social Dialogues archive contained no JSON rows")
    return reservoir


def _deduplicate(records: Iterable[dict[str, Any]]) -> list[dict[str, Any]]:
    seen: set[str] = set()
    output: list[dict[str, Any]] = []
    for record in records:
        canonical = json.dumps(record["messages"], ensure_ascii=False, sort_keys=True)
        digest = hashlib.sha256(canonical.encode("utf-8")).hexdigest()
        if digest in seen:
            continue
        seen.add(digest)
        output.append(record)
    return output


def _write_jsonl(records: list[dict[str, Any]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".part")
    try:
        with temporary.open("w", encoding="utf-8") as stream:
            for record in records:
                stream.write(json.dumps(record, ensure_ascii=False, separators=(",", ":")) + "\n")
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)


def prepare(
    *,
    output: Path,
    manifest_output: Path,
    max_examples_per_source: int,
    seed: int,
    append_to: Path | None = None,
) -> dict[str, Any]:
    all_records: list[dict[str, Any]] = []
    manifest: dict[str, Any] = {
        "format": "catai-first-wave-chat-datasets",
        "version": 1,
        "seed": seed,
        "max_examples_per_source": max_examples_per_source,
        "sources": {},
        "errors": [],
    }

    for index, (source, spec) in enumerate(PAGE_SOURCES.items()):
        try:
            rows = sample_viewer_rows(
                spec["repository"], spec["config"], spec["split"],
                max_examples_per_source, seed + index,
            )
            converted: list[dict[str, Any]] = []
            for row_index, row in enumerate(rows):
                messages = CONVERTERS[source](row)
                if messages is None:
                    continue
                converted.append(make_record(
                    source,
                    messages,
                    repository=spec["repository"],
                    license_name=spec["license"],
                    attribution=spec["attribution"],
                    split=spec["split"],
                    source_id=row.get("id", row.get("dialogue_id", row.get("original_index", row_index))),
                    notes=spec["notes"],
                ))
            random.Random(seed + index).shuffle(converted)
            converted = _deduplicate(converted)[:max_examples_per_source]
            if not converted:
                raise RuntimeError("no sampled rows converted into valid user/assistant conversations")
            manifest["sources"][source] = {
                **spec,
                "sampled_rows": len(rows),
                "usable_examples": len(converted),
            }
            all_records.extend(converted)
        except Exception as exc:
            manifest["errors"].append({
                "source": source,
                "error": f"{type(exc).__name__}: {exc}",
            })

    try:
        multiwoz = _download_multiwoz_examples(max_examples_per_source, seed + 100)
        if not multiwoz:
            raise RuntimeError("no MultiWOZ dialogues converted into valid conversations")
        all_records.extend(multiwoz)
        manifest["sources"]["multiwoz"] = {
            **MULTIWOZ_SPEC,
            "split": "train",
            "sampled_examples": len(multiwoz),
            "usable_examples": len(multiwoz),
            "integrity": "SHA-256 verified against Hugging Face dataset_infos.json",
        }
    except Exception as exc:
        manifest["errors"].append({
            "source": "multiwoz",
            "error": f"{type(exc).__name__}: {exc}",
        })

    try:
        rows = _download_social_dialogue_rows(max_examples_per_source, seed + 101)
        converted = []
        for row_index, row in enumerate(rows):
            messages = convert_synthetic_social_dialogues_row(row)
            if messages is None:
                continue
            converted.append(make_record(
                "synthetic_social_dialogues",
                messages,
                repository=SOCIAL_DIALOGUE_SPEC["repository"],
                license_name=SOCIAL_DIALOGUE_SPEC["license"],
                attribution=SOCIAL_DIALOGUE_SPEC["attribution"],
                split="train",
                source_id=row.get("id", row_index),
                notes=SOCIAL_DIALOGUE_SPEC["notes"],
            ))
        converted = _deduplicate(converted)[:max_examples_per_source]
        if not converted:
            raise RuntimeError("no sampled social-dialogue rows converted into valid conversations")
        manifest["sources"]["synthetic_social_dialogues"] = {
            **SOCIAL_DIALOGUE_SPEC,
            "sampled_rows": len(rows),
            "usable_examples": len(converted),
            "download": "official Hugging Face train.jsonl.zst; Zstandard decompressed",
        }
        all_records.extend(converted)
    except Exception as exc:
        manifest["errors"].append({
            "source": "synthetic_social_dialogues",
            "error": f"{type(exc).__name__}: {exc}",
        })

    # Fail closed: an incomplete six-source wave must not silently enter training.
    expected_sources = set(PAGE_SOURCES) | {"multiwoz", "synthetic_social_dialogues"}
    missing = expected_sources - set(manifest["sources"])
    if missing:
        manifest_output.parent.mkdir(parents=True, exist_ok=True)
        manifest["missing_sources"] = sorted(missing)
        manifest_output.write_text(
            json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
            encoding="utf-8",
        )
        raise RuntimeError(
            "First-wave dataset preparation is incomplete; missing: "
            + ", ".join(sorted(missing))
            + f". See {manifest_output}."
        )

    all_records = _deduplicate(all_records)
    random.Random(seed).shuffle(all_records)
    _write_jsonl(all_records, output)
    manifest["outputs"] = {
        "chat": str(output),
        "usable_examples": len(all_records),
    }
    if append_to is not None:
        existing: list[dict[str, Any]] = []
        if append_to.is_file():
            with append_to.open("r", encoding="utf-8") as stream:
                for line_number, line in enumerate(stream, start=1):
                    if not line.strip():
                        continue
                    try:
                        item = json.loads(line)
                    except json.JSONDecodeError as exc:
                        raise ValueError(
                            f"invalid JSON in existing SFT dataset at line {line_number}"
                        ) from exc
                    if not isinstance(item, dict):
                        raise ValueError(
                            f"existing SFT dataset line {line_number} must be an object"
                        )
                    existing.append(item)
        combined = _deduplicate([*existing, *all_records])
        _write_jsonl(combined, append_to)
        manifest["outputs"]["merged_sft_chat"] = str(append_to)
        manifest["outputs"]["merged_sft_examples"] = len(combined)
    manifest["total_sources"] = len(manifest["sources"])
    manifest_output.parent.mkdir(parents=True, exist_ok=True)
    manifest_output.write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Prepare CatAI's first-wave conversational datasets with license provenance."
    )
    parser.add_argument("--max-examples-per-source", type=int, default=1000)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--output", type=Path, default=Path("data/first_wave_chat.jsonl"))
    parser.add_argument(
        "--manifest-output",
        type=Path,
        default=Path("data/first_wave_datasets_manifest.json"),
    )
    parser.add_argument(
        "--append-to",
        type=Path,
        default=None,
        help="Also merge these records into an existing SFT JSONL file.",
    )
    args = parser.parse_args()
    if args.max_examples_per_source < 1 or args.seed < 0:
        raise ValueError("max-examples-per-source must be positive and seed non-negative")
    manifest = prepare(
        output=args.output,
        manifest_output=args.manifest_output,
        max_examples_per_source=args.max_examples_per_source,
        seed=args.seed,
        append_to=args.append_to,
    )
    print(
        f"Prepared {manifest['outputs']['usable_examples']:,} first-wave chat examples "
        f"from {manifest['total_sources']} sources."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
